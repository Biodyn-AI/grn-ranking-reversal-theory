PROJECT = Path(__file__).resolve().parent
INPUTS = PROJECT / "inputs"
OUTPUTS = PROJECT / "outputs"
FIGURES = OUTPUTS / "figures"
CANDIDATES = ["all_pairs", "tf_sources", "tf_sources_targets"]
CANDIDATE_LABELS = {"all_pairs": "All pairs", "tf_sources": "TF sources", "tf_sources_targets": "TF sources + targets"}
plt.rcParams.update({"font.family": "sans-serif", "font.sans-serif": ["Arial", "DejaVu Sans"], "font.size": 10, "axes.titlesize": 11, "axes.labelsize": 10})


def export(figure, number):
    """Keep exact physical dimensions instead of tight-bbox DPI inflation."""
    figure.savefig(FIGURES / f"Fig{number}.png", dpi=300)
    plt.close(figure)
    export_tiff(FIGURES / f"Fig{number}.png", number)


def export_tiff(source, number):
    with Image.open(source) as original:
        pixels = original.convert("RGB")
        scale = min(1.0, 2250 / pixels.width, 2625 / pixels.height)
        if scale < 1:
            pixels = pixels.resize((round(pixels.width * scale), round(pixels.height * scale)), Image.Resampling.LANCZOS)
        pixels.save(FIGURES / f"Fig{number}.png", dpi=(300, 300))
        pixels.save(FIGURES / f"Fig{number}.tif", dpi=(300, 300), compression="tiff_lzw")


def heatmap(axis, row_column, row_values, transitions, title, number):
    cells = pd.read_csv(OUTPUTS / "protocol_cell_rates.csv")
    cells = cells[cells["axis"] == axis]
    values = np.zeros((len(row_values), len(transitions)))
    labels = np.empty_like(values, dtype=object)
    for i, row_value in enumerate(row_values):
        for j, (from_column, to_column, first, second) in enumerate(transitions):
            cell = cells[(cells[row_column] == row_value) & (cells[from_column] == first) & (cells[to_column] == second)].iloc[0]
            values[i, j] = cell["rate"]
            labels[i, j] = f"{int(cell['k'])}/{int(cell['n'])}"
    figure, ax = plt.subplots(figsize=(7.1, 3.4), layout="constrained")
    plot = ax.imshow(values, cmap="Blues", vmin=0, vmax=0.5, aspect="auto")
    ax.set_yticks(range(len(row_values)), [CANDIDATE_LABELS.get(value, value.capitalize()) for value in row_values])
    ax.set_xticks(range(len(transitions)), [f"{CANDIDATE_LABELS.get(first, first.capitalize())}\n↔ {CANDIDATE_LABELS.get(second, second.capitalize())}" for _, _, first, second in transitions])
    for index, label in np.ndenumerate(labels):
        ax.text(index[1], index[0], label, ha="center", va="center", color="white" if values[index] > 0.30 else "black")
    ax.set_title(title)
    figure.colorbar(plot, ax=ax, label="Reversal fraction", shrink=0.9)
    export(figure, number)


REFERENCE_NAMES = {"beeline_gsd": "BEELINE", "dorothea_trrust_union_immune": "DoRothEA/TRRUST", "hpn_dream": "HPN-DREAM"}
AXIS_COLORS = {"candidate": "#24556d", "tissue": "#c0763a", "reference": "#5b8c3a"}
METHOD_NAMES = {"genie3": "GENIE3", "grnboost2": "GRNBoost2", "pearson": "Pearson", "spearman": "Spearman",
                "random": "random", "scgpt_attention": "scGPT attention", "scenic_grnboost2": "SCENIC GRNBoost2",
                "scenic_pruned": "SCENIC pruned", "pidc_proxy": "PIDC proxy", "pidc_full": "PIDC full"}


def reference_figure():
    """Recovered edges, informative endpoints, and margins in base-rate units."""
    endpoints = pd.read_csv(OUTPUTS / "extended_reference_endpoints.csv")
    summary = pd.read_csv(OUTPUTS / "extended_reference_summary.csv")
    figure = plt.figure(figsize=(7.1, 6.2), layout="constrained")
    grid = figure.add_gridspec(2, 2, height_ratios=[1.05, 1], width_ratios=[0.88, 1.12])
    ax = figure.add_subplot(grid[0, 0])
    references = ["hpn_dream", "beeline_gsd", "dorothea_trrust_union_immune"]
    methods = sorted(endpoints["method"].unique())
    counts = endpoints.pivot(index="method", columns="reference", values="recovered_edges").loc[methods, references]
    ax.imshow(np.log10(counts.to_numpy() + 1), cmap="Greens", vmin=0, vmax=3, aspect="auto")
    for (i, j), value in np.ndenumerate(counts.to_numpy()):
        ax.text(j, i, str(int(value)), ha="center", va="center", fontsize=8,
                color="white" if value > 150 else "black")
    ax.set_xticks(range(3), ["HPN-\nDREAM", "BEELINE", "DoRothEA/\nTRRUST"])
    ax.set_yticks(range(len(methods)), [METHOD_NAMES[m] for m in methods], fontsize=8)
    ax.set_title("A  Reference edges recovered", loc="left")
    ax = figure.add_subplot(grid[0, 1])
    transitions = summary[(summary["reference_from"] != "all")]
    order = [("beeline_gsd", "hpn_dream"), ("beeline_gsd", "dorothea_trrust_union_immune"),
             ("dorothea_trrust_union_immune", "hpn_dream")]
    colors = {0: "#b9b9b9", 1: "#5b8c3a"}
    for x, (first, second) in enumerate(order):
        bottom = 0
        for informative in (0, 1):
            cell = transitions[(transitions["reference_from"] == first) & (transitions["reference_to"] == second)
                               & (transitions["n_informative_endpoints"] == informative)]
            if cell.empty:
                continue
            n, k = int(cell["n"].iloc[0]), int(cell["k"].iloc[0])
            ax.bar(x, n, bottom=bottom, color=colors[informative], width=0.62,
                   label={0: "No endpoint informative", 1: "One endpoint informative"}[informative]
                   if x == 1 else None)
            ax.text(x, bottom + n / 2, f"{k}/{n}", ha="center", va="center", fontsize=8)
            bottom += n
    ax.set_xticks(range(3), [f"{REFERENCE_NAMES[a]}\n↔\n{REFERENCE_NAMES[b]}" for a, b in order], fontsize=8)
    ax.set_ylabel("Eligible comparisons")
    ax.set_ylim(0, 44)
    ax.legend(fontsize=8, frameon=False, loc="upper right")
    ax.set_title("B  Reversals by transition", loc="left")
    ax = figure.add_subplot(grid[1, :])
    frames = {"candidate": "candidate_shift_pairwise_rows.csv",
              "tissue": "tissue_shift_pairwise_rows_candidate_conditional.csv"}
    margins = {}
    base = pd.read_csv(INPUTS / "table_a2.csv").groupby("candidate_set")["base_rate_median"].first()
    for axis, name in frames.items():
        rows = pd.read_csv(INPUTS / name)
        if axis == "tissue":
            rows["base_rate_from"] = rows["candidate_set"].map(base)
            rows["base_rate_to"] = rows["base_rate_from"]
        margins[axis] = rows.assign(m=np.minimum(rows["delta_from"].abs() / rows["base_rate_from"],
                                                 rows["delta_to"].abs() / rows["base_rate_to"]))
    reference_rows = pd.read_csv(OUTPUTS / "extended_reference_rows.csv")
    margins["reference"] = reference_rows.assign(m=reference_rows["min_normalized_margin"])
    rng = np.random.default_rng(1)
    labels = {"candidate": "Candidate set", "tissue": "Tissue", "reference": "Reference (immune)"}
    for y, axis in enumerate(["candidate", "tissue", "reference"]):
        rows = margins[axis]
        for reversal, marker, face in [(False, "o", "none"), (True, "o", AXIS_COLORS[axis])]:
            subset = rows[rows["reversal"] == reversal]
            jitter = rng.uniform(-0.18, 0.18, len(subset)) + (0.12 if reversal else -0.12)
            ax.scatter(np.log10(subset["m"].clip(lower=1e-9)), y + jitter, s=13, marker=marker,
                       facecolors=face, edgecolors=AXIS_COLORS[axis], linewidths=0.7, alpha=0.85)
    ax.axvline(-3, color="0.35", linestyle="--", linewidth=0.9)
    ax.text(-2.95, 2.45, "0.1% of base rate", fontsize=8, va="center")
    ax.set_yticks(range(3), [labels[a] for a in ["candidate", "tissue", "reference"]])
    ax.set_ylim(2.6, -0.6)
    ax.set_xlabel("log10 of smaller endpoint margin / endpoint positive base rate")
    ax.scatter([], [], s=13, facecolors="0.4", edgecolors="0.4", label="Reversal")
    ax.scatter([], [], s=13, facecolors="none", edgecolors="0.4", label="No reversal")
    ax.legend(fontsize=8, frameon=False, loc="lower left", ncol=2)
    ax.set_title("C  Endpoint margins on a common base-rate scale", loc="left")
    export(figure, 4)


def accounting_figure():
    curves = pd.read_csv(OUTPUTS / "algebra_population_prevalence.csv")
    directions = pd.read_csv(OUTPUTS / "algebra_direction_summary.csv")
    figure, axes = plt.subplots(1, 2, figsize=(7.4, 3.8), layout="constrained")
    ax = axes[0]
    fractions = directions["dominance_fraction_on_reversal"]
    bars = ax.bar(range(2), fractions, color=["#24556d", "#a94257"])
    for bar, row in zip(bars, directions.itertuples()):
        ax.text(bar.get_x()+bar.get_width()/2, bar.get_height()+0.03, f"{row.dominant_on_reversal}/{row.reversals}", ha="center")
    ax.set_xticks(range(2), ["Recorded endpoints\nIncreasing base rate", "Reversed endpoints\nDecreasing base rate"])
    ax.set_ylim(0, 1.16)
    ax.set_title("A  Same 22 observed reversals", loc="left")
    ax.set_ylabel("Fraction with |gap term| > |base-rate term|")
    ax = axes[1]
    ax.semilogx(curves["base_rate"], curves["aupr_a"], color="#24556d", label="Constructed method A")
    ax.semilogx(curves["base_rate"], curves["aupr_b"], color="#a94257", label="Constructed method B")
    observed = curves[curves["is_observed_base_rate"]]
    for rate in observed["base_rate"]:
        ax.axvline(rate, color="0.65", linestyle=":", linewidth=0.8)
    ax.set_xlim(1e-5, 0.03)
    ax.set_ylim(0, 0.36)
    ax.set_title("B  Illustration: fixed ROC curves", loc="left")
    ax.set_xlabel("Positive base rate")
    ax.set_ylabel("Population AUPR")
    ax.legend(loc="upper left", fontsize=8, frameon=False)
    export(figure, 2)


def metric_figure():
    """Matched-key reversal counts, their membership, and rounding ambiguity."""
    summary = pd.read_csv(OUTPUTS / "protocol_metric_summary.csv")
    matched = pd.read_csv(OUTPUTS / "protocol_metric_matched_rows.csv")
    rounding = pd.read_csv(OUTPUTS / "extended_metric_rounding_keys.csv")
    metrics = ["AUPR", "AUROC", "F1"]
    colors = ["#24556d", "#c0763a", "#7a4a8c"]
    figure = plt.figure(figsize=(7.4, 5.6), layout="constrained")
    grid = figure.add_gridspec(2, 2)
    ax = figure.add_subplot(grid[0, 0])
    for x, (metric, color) in enumerate(zip(metrics, colors)):
        row = summary[(summary["scope"] == "all_three_metrics_matched") & (summary["metric"] == metric)].iloc[0]
        ax.bar(x, row["k"], color=color, width=0.6)
        ax.text(x, row["k"] + 0.08, f"{int(row['k'])}/{int(row['n'])}", ha="center")
    ax.set_xticks(range(3), metrics)
    ax.set_ylim(0, 3)
    ax.set_yticks([0, 1, 2, 3])
    ax.set_ylabel("Reversals")
    ax.set_title("A  Same 40 non-tied keys", loc="left")
    ax = figure.add_subplot(grid[0, 1])
    keys = matched[matched[metrics].astype(bool).any(axis=1)]
    heat = keys[metrics].astype(int).to_numpy()
    ax.imshow(heat, cmap="Blues", vmin=0, vmax=1, aspect="auto")
    ax.set_xticks(range(3), metrics)
    ax.set_yticks(range(len(keys)), [f"{r.tissue_from}–{r.tissue_to}\n{METHOD_NAMES[r.method_a]}–{METHOD_NAMES[r.method_b]}"
                                     for r in keys.itertuples(index=False)], fontsize=8)
    for (i, j), value in np.ndenumerate(heat):
        ax.text(j, i, "Reverse" if value else "Stable", ha="center", va="center",
                color="white" if value else "black", fontsize=8)
    ax.set_title("B  Matched reversals", loc="left")
    ax = figure.add_subplot(grid[1, :])
    auroc = rounding[(rounding["metric"] == "AUROC") & ~rounding["in_matched_set"]]
    labels = [f"{r.tissue_from}–{r.tissue_to}: {METHOD_NAMES[r.method_a]}–{METHOD_NAMES[r.method_b]}"
              for r in auroc.itertuples(index=False)]
    ax.barh(range(len(auroc)), auroc["reversal_probability"], color="#c0763a", height=0.55)
    for y, value in enumerate(auroc["reversal_probability"]):
        ax.text(value + 0.01, y, f"{value:.2f}", va="center", fontsize=8)
    ax.set_yticks(range(len(auroc)), labels, fontsize=8)
    ax.invert_yaxis()
    ax.set_xlim(0, 1)
    ax.set_xlabel("AUROC reversal probability over rounding-consistent values")
    ax.set_title("C  AUROC-tied keys when printed values are rounding intervals", loc="left")
    export(figure, 7)


def screening_supplement_figure():
    """Permutation null and planted-signal power for the held-out-tissue screens."""
    summary = json.loads((OUTPUTS / "extended_summary.json").read_text())["screening"]
    nulls = pd.read_csv(OUTPUTS / "extended_screening_null_draws.csv")
    power = pd.read_csv(OUTPUTS / "extended_screening_power.csv")
    figure, axes = plt.subplots(1, 2, figsize=(7.4, 3.6), layout="constrained")
    ax = axes[0]
    bins = np.linspace(0.05, 0.5, 40)
    for name, column, color in [("logistic", "logistic_ap", "#7a4a8c"), ("heuristic", "heuristic_ap", "#24556d")]:
        ax.hist(nulls[column], bins=bins, color=color, alpha=0.45, label=f"{name.capitalize()} null")
        ax.axvline(summary[name]["observed_ap"], color=color, linewidth=1.8)
    ax.axvline(summary["prevalence"], color="0.3", linestyle="--", linewidth=1, label="Prevalence 0.163")
    ax.set_xlabel("Pooled held-out average precision")
    ax.set_ylabel("Permutations")
    ax.legend(fontsize=8, frameon=False)
    ax.set_title("Within-fold label permutations", loc="left")
    ax = axes[1]
    ax.plot(power["planted_auroc"], power["power_at_random_q95"], "o-", color="#24556d")
    ax.axhline(0.8, color="0.6", linestyle=":", linewidth=1)
    ax.set_xlabel("AUROC of a planted fixed score")
    ax.set_ylabel("P(AP above random-ranking 95th percentile)")
    ax.set_ylim(0, 1.03)
    ax.set_title("Detection power, 22 positives", loc="left")
    figure.savefig(FIGURES / "S1_FigB.png", dpi=300)
    plt.close(figure)


def margin_figure():
    sweeps = pd.read_csv(OUTPUTS / "protocol_margin_sweep.csv")
    figure, axes = plt.subplots(2, 2, figsize=(7.1, 5.4), layout="constrained", sharex=True, sharey=True)
    titles = {"candidate": "Candidate set", "tissue": "Tissue", "reference": "Reference: immune only", "mapping": "Mapping: probe panel"}
    for ax, axis in zip(axes.flat, titles):
        sweep = sweeps[sweeps["axis"] == axis]
        x = sweep["quantile"].to_numpy()
        ax.fill_between(x, sweep["ci_low"], sweep["ci_high"], color="#337999", alpha=0.18)
        ax.plot(x, sweep["rate"], "o-", color="#24556d")
        ax.set_title(titles[axis])
        ax.set_ylim(-0.035, 0.60)
        ax.set_xticks([0, 0.25, 0.5, 0.75])
        ax.text(0.03, 0.96, f"N: {int(sweep.iloc[0]['n'])} → {int(sweep.iloc[-1]['n'])}", va="top", transform=ax.transAxes)
        ax.grid(alpha=0.15)
    for ax in axes[-1]:
        ax.set_xlabel("Endpoint-margin quantile floor")
    for ax in axes[:, 0]:
        ax.set_ylabel("Reversal fraction")
    export(figure, 5)


def main():
    FIGURES.mkdir(parents=True, exist_ok=True)
    candidate_transitions = [("shift_from", "shift_to", CANDIDATES[i], CANDIDATES[j]) for i, j in [(0, 1), (0, 2), (1, 2)]]
    heatmap("candidate", "gene_set", ["immune", "kidney", "lung"], candidate_transitions, "Candidate transitions across three tissues", 1)
    accounting_figure()
    tissue_transitions = [("tissue_from", "tissue_to", first, second) for first, second in [("immune", "kidney"), ("immune", "lung"), ("kidney", "lung")]]
    heatmap("tissue", "candidate_set", CANDIDATES, tissue_transitions, "Tissue transitions under each candidate definition", 3)
    reference_figure()
    margin_figure()
    # The control panel is rendered by algebra_null.py from its verified outputs.
    export_tiff(FIGURES / "algebra_label_noise_controls.png", 6)
    metric_figure()
    # Supporting figures for S1 Text: the screening audit panel and its feasibility checks.
    shutil.copyfile(FIGURES / "protocol_screening_audit.png", FIGURES / "S1_FigA.png")
    screening_supplement_figure()
    for stale in ("Fig8.png", "Fig8.tif"):
        (FIGURES / stale).unlink(missing_ok=True)
    print(f"Rendered seven PNG/TIFF figure pairs and two S1 Text figures in {FIGURES}")


if __name__ == "__main__":
    main()
